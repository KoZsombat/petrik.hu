/**
 * Collects the category, date and author archives from the mirror and writes
 * them to src/data/archives.ts.
 *
 * All three families share one template, so a single component renders them;
 * what differs is which posts each one lists, in what order, and where its
 * pagination points. None of that is recomputed here. WordPress's ordering,
 * its per-taxonomy page size (12 for categories and dates, 5 for authors) and
 * its tie-breaks are all already written down in the mirror, and reproducing
 * them would be guesswork that stays invisible until someone diffs a page.
 *
 *   node --experimental-strip-types scripts/archives.ts
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { parse } from 'node-html-parser'
import { MIRROR_ROOT, PROJECT_ROOT } from './mirror.ts'
import { resolveUrl } from './extract.ts'

const q = (value: string) => JSON.stringify(value)

/** Every directory under `root` that holds an index.html, depth-first. */
function archiveDirs(root: string): string[] {
  const out: string[] = []
  const walk = (rel: string) => {
    const abs = join(MIRROR_ROOT, rel)
    if (!existsSync(abs)) return
    if (existsSync(join(abs, 'index.html'))) out.push(rel)
    for (const item of readdirSync(abs, { withFileTypes: true })) {
      // `feed` directories hold the RSS copies of the same listing.
      if (item.isDirectory() && item.name !== 'feed') walk(`${rel}/${item.name}`)
    }
  }
  walk(root)
  return out
}

/** Year directories, which hold the month and day archives. */
function dateDirs(): string[] {
  return readdirSync(MIRROR_ROOT, { withFileTypes: true })
    .filter((item) => item.isDirectory() && /^[0-9]{4}$/.test(item.name))
    .flatMap((item) => archiveDirs(item.name))
}

type Archive = {
  route: string
  kind: 'category' | 'author' | 'date'
  label: string
  slugs: string[]
  older?: string
  newer?: string
  olderMissing?: boolean
  newerMissing?: boolean
}

const dirs = [...archiveDirs('kategoria'), ...archiveDirs('author'), ...dateDirs()].sort()
const archives: Archive[] = []
const problems: string[] = []
const report = (message: string) => {
  problems.push(message)
  console.error(`  ! ${message}`)
}

for (const dir of dirs) {
  const root = parse(readFileSync(join(MIRROR_ROOT, dir, 'index.html'), 'utf8'))
  const left = root.querySelector('#left-area')
  if (!left) {
    report(`${dir}: no #left-area`)
    continue
  }

  const slugs = left
    .querySelectorAll('article.et_pb_post .entry-title a')
    .map((link) => resolveUrl(link.getAttribute('href') ?? '', dir))
    .map((url) => url.replace(/^\/|\/$/g, ''))
    .filter(Boolean)

  // The only human-readable name an archive has: the DOM carries no heading.
  const label = (root.querySelector('title')?.text ?? '')
    .replace(/\s*\|\s*petrik\.hu\s*$/, '')
    .trim()
  if (!label) report(`${dir}: no title`)

  const pagination = left.querySelector('.pagination')
  const target = (side: string) => {
    const link = pagination?.querySelector(`.${side} a`)
    if (!link) return undefined
    return resolveUrl(link.getAttribute('href') ?? '', dir)
  }

  archives.push({
    route: `/${dir}/`,
    kind: dir.startsWith('kategoria/') ? 'category' : dir.startsWith('author/') ? 'author' : 'date',
    label,
    slugs,
    older: target('alignleft'),
    newer: target('alignright'),
  })
}

/**
 * The crawl stopped before the end of several listings, so some "older posts"
 * links point at a page that was never saved. Marking them here is what lets
 * the pagination render the control as inert text instead of a link into a 404.
 */
const known = new Set(archives.map((archive) => archive.route))
let dangling = 0
for (const archive of archives) {
  if (archive.older && !known.has(archive.older)) {
    archive.olderMissing = true
    dangling += 1
  }
  if (archive.newer && !known.has(archive.newer)) {
    archive.newerMissing = true
    dangling += 1
  }
}

/* -- write ----------------------------------------------------------------- */

const entries = archives.map((archive) =>
  [
    `  ${q(archive.route)}: {`,
    `    route: ${q(archive.route)},`,
    `    kind: ${q(archive.kind)},`,
    `    label: ${q(archive.label)},`,
    `    slugs: [`,
    ...archive.slugs.map((slug) => `      ${q(slug)},`),
    `    ],`,
    ...(archive.older ? [`    older: ${q(archive.older)},`] : []),
    ...(archive.olderMissing ? ['    olderMissing: true,'] : []),
    ...(archive.newer ? [`    newer: ${q(archive.newer)},`] : []),
    ...(archive.newerMissing ? ['    newerMissing: true,'] : []),
    '  },',
  ].join('\n'),
)

const source = [
  '/**',
  ' * The category, date and author archives, as the mirror lists them.',
  ' * Generated by scripts/archives.ts - do not edit by hand.',
  ' *',
  ' * The post order and the page size are transcribed rather than recomputed:',
  ' * WordPress paged categories and dates by twelve and authors by five, and',
  ' * re-deriving its ordering would be guesswork. One component renders all of',
  ' * them, keyed by route.',
  ' */',
  '',
  "export type ArchiveKind = 'category' | 'author' | 'date'",
  '',
  'export type Archive = {',
  "  /** Route in the ported site, identical to the mirror's directory path. */",
  '  route: string',
  '  kind: ArchiveKind',
  '  /**',
  "   * The mirror's <title> without the site name. There is no heading anywhere",
  '   * in the markup, so this is the only name an archive has - and the date',
  '   * archives share the single label "Archívum".',
  '   */',
  '  label: string',
  "  /** Post slugs, in the mirror's order. */",
  '  slugs: string[]',
  '  /** Where "« Régebbi bejegyzések" pointed, when the mirror printed it. */',
  '  older?: string',
  '  /** Where "Újabb bejegyzések »" pointed. */',
  '  newer?: string',
  '  /**',
  '   * The target was linked but never captured, so the control is rendered',
  '   * without a link rather than sending the reader into a 404.',
  '   */',
  '  olderMissing?: boolean',
  '  newerMissing?: boolean',
  '}',
  '',
  'export const archives: Record<string, Archive> = {',
  ...entries,
  '}',
  '',
  '/** Looks an archive up by pathname, as the router reports it. */',
  'export function archiveAt(pathname: string): Archive | undefined {',
  '  return archives[pathname]',
  '}',
  '',
]

const out = resolve(PROJECT_ROOT, 'src/data/archives.ts')
writeFileSync(out, source.join('\n'), 'utf8')

const counts = { category: 0, author: 0, date: 0 }
for (const archive of archives) counts[archive.kind] += 1
const posts = new Set(archives.flatMap((archive) => archive.slugs))
console.log(
  `archives: ${archives.length} (${counts.category} category, ${counts.date} date, ` +
    `${counts.author} author), ${posts.size} distinct posts, ` +
    `${dangling} pagination targets not in the snapshot -> src/data/archives.ts`,
)
if (problems.length) process.exit(1)
