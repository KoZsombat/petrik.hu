/**
 * Collects every mirrored page's <head> metadata into src/data/head.ts.
 *
 *   node --experimental-strip-types scripts/head.ts
 *
 * A single-page app has one <head> in index.html, so without this every route
 * would share the site's title and nothing else. What is collected is what the
 * mirror actually has, which is less than one might assume:
 *
 *   - <title>              on all 345 mirrored pages
 *   - <meta description>   on exactly one, the home page
 *   - <meta robots>        on all 345, and only /hirkezelo/ - which is not
 *                          ported - carries anything but
 *                          `max-image-preview:large`
 *   - <link canonical>     on 269; the date archives and 75 others have none
 *   - Open Graph, Twitter  on none at all
 *
 * The titles are transcribed rather than composed from the page headings:
 * WordPress built them from the post title, the taxonomy label and Yoast's
 * template, and several pages do not carry their title anywhere in the body -
 * the date archives are all just "Archívum".
 *
 * The canonical is the one thing that cannot be transcribed. Every href in the
 * mirror was rewritten by the crawler to a relative path ("", "index.html",
 * "../bemutatkozas/"), so the original absolute URL is gone from all 269. What
 * is certain is what it pointed at: WordPress emits a self-canonical, the page's
 * own URL. That is why only its presence is recorded here, and the component
 * resolves it against wherever the port is being served - no invented domain.
 */
import { readFileSync, existsSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { MIRRORED } from './pages.ts'
import { MIRROR_ROOT, PROJECT_ROOT } from './mirror.ts'

/*
 * WordPress and its plugins quote attributes both ways in the same document -
 * Yoast writes `name='robots'` with single quotes while the theme writes
 * `rel="canonical"` with double - so every pattern here has to take either.
 * Matching only double quotes found the robots meta on 25 of the ported routes
 * instead of all 129, and check-head.ts caught it - which is the point of
 * having a checker that reads the rendered page rather than the generator's
 * own idea of what it parsed.
 */
const TITLE_RE = /<title>([\s\S]*?)<\/title>/
const DESCRIPTION_RE = /<meta\s+name=["']description["']\s+content=["']([^"']*)["']/
const ROBOTS_RE = /<meta\s+name=["']robots["']\s+content=["']([^"']*)["']/
const CANONICAL_RE = /<link\s+rel=["']canonical["']/

/** The few entities WordPress writes into a title or a description. */
function decode(text: string): string {
  return text
    .replace(/&#(\d+);/g, (_, code: string) => String.fromCodePoint(Number(code)))
    .replace(/&#x([0-9a-f]+);/gi, (_, code: string) => String.fromCodePoint(parseInt(code, 16)))
    .replace(/&quot;/g, '"')
    .replace(/&apos;|&#0?39;/g, "'")
    .replace(/&nbsp;/g, ' ')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&amp;/g, '&')
}

const q = (text: string) => JSON.stringify(text)

type Head = {
  route: string
  title: string
  description?: string
  robots?: string
  canonical: boolean
}

const heads: Head[] = []
const problems: string[] = []

for (const page of MIRRORED) {
  const file = join(MIRROR_ROOT, page.dir, 'index.html')
  if (!existsSync(file)) {
    problems.push(`  ! no mirror page for ${page.route}`)
    continue
  }
  const html = readFileSync(file, 'utf8')
  const head = html.slice(0, html.indexOf('</head>'))
  const title = decode(TITLE_RE.exec(html)?.[1] ?? '').trim()
  if (!title) {
    problems.push(`  ! no <title> in ${page.dir}/index.html`)
    continue
  }
  const description = decode(DESCRIPTION_RE.exec(head)?.[1] ?? '').trim()
  const robots = ROBOTS_RE.exec(head)?.[1]?.trim()
  heads.push({
    route: page.route,
    title,
    description: description || undefined,
    robots: robots || undefined,
    canonical: CANONICAL_RE.test(head),
  })
}

for (const problem of problems) console.error(problem)
if (!heads.some((entry) => entry.route === '/')) problems.push('  ! the home page has no title')

/*
 * The home page's title is the site name on its own; every other page is
 * "<page> | petrik.hu". The suffix is not stripped - it is part of what the
 * original put in the tab, and the archives' label field already holds the
 * stripped form for the pages that need one.
 */
function entry(head: Head): string {
  const fields = [`title: ${q(head.title)}`]
  if (head.description) fields.push(`description: ${q(head.description)}`)
  if (head.robots) fields.push(`robots: ${q(head.robots)}`)
  if (head.canonical) fields.push('canonical: true')
  return `  ${q(head.route)}: { ${fields.join(', ')} },`
}

const source = [
  '/**',
  " * Every mirrored page's <head>, keyed by route.",
  ' * Generated by scripts/head.ts - do not edit by hand.',
  ' *',
  ' * A single-page app has one <head> in index.html, so useDocumentHead applies',
  ' * these as the route changes. Everything here is transcribed from the mirror;',
  ' * see scripts/head.ts for what the mirror does and does not carry.',
  ' */',
  '',
  'export type PageHead = {',
  '  title: string',
  '  /** Only the home page has one. */',
  '  description?: string',
  '  robots?: string',
  '  /**',
  "   * The mirror had a canonical link here. Its href was rewritten by the",
  '   * crawler, so only the fact is recorded; WordPress emitted a self-canonical,',
  "   * which the component resolves against the page's own URL.",
  '   */',
  '  canonical?: true',
  '}',
  '',
  'export const heads: Record<string, PageHead> = {',
  ...heads.map(entry),
  '}',
  '',
]

const out = resolve(PROJECT_ROOT, 'src/data/head.ts')
writeFileSync(out, source.join('\n'), 'utf8')
console.log(
  `head: ${heads.length}/${MIRRORED.length} routes ` +
    `(${heads.filter((h) => h.description).length} with a description, ` +
    `${heads.filter((h) => h.robots).length} with robots, ` +
    `${heads.filter((h) => h.canonical).length} canonical) -> src/data/head.ts` +
    (problems.length ? ` (${problems.length} problems above)` : ''),
)
if (problems.length) process.exit(1)
