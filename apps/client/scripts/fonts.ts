/**
 * Rebuilds the site's webfont stylesheet from the mirror.
 *
 * WordPress inlined a full Google Fonts payload (every weight, in both a legacy
 * .ttf and a modern .woff2 flavour — ~32 KB of @font-face rules alone). We keep
 * the .woff2 faces at the weights the design uses, copy them into public/fonts,
 * and repoint the URLs there so nothing is fetched from fonts.gstatic.com at
 * runtime.
 *
 * Note: Google served these without unicode-range, so each file carries every
 * requested subset (latin, latin-ext, greek, cyrillic, vietnamese) — hence
 * ~55 KB per face. That is also why Hungarian accents resolve from one file.
 *
 *   node --experimental-strip-types scripts/fonts.ts
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, resolve } from 'node:path'
import { FONT_DIR, MIRROR_ROOT, PROJECT_ROOT } from './mirror.ts'
import { PAGES } from './pages.ts'

/** Inline <style> blocks in the mirror that carry @font-face rules. */
const FONT_STYLE_IDS = ['et-divi-open-sans-inline-css', 'et-builder-googlefonts-cached-inline']

/** Weights the Divi customizer and the page designs actually reference. */
const KEEP_WEIGHTS = new Set([300, 400, 500, 600, 700, 800])

type Face = {
  family: string
  style: string
  weight: number
  src: string
  block: string
}

function readStyleBlock(html: string, id: string): string {
  const match = new RegExp(`<style[^>]*id="${id}"[^>]*>([^]*?)</style>`).exec(html)
  if (!match) throw new Error(`no inline style block with id="${id}"`)
  return match[1]
}

function parseFaces(css: string): Face[] {
  const faces: Face[] = []
  for (const chunk of css.split('@font-face')) {
    const block = chunk.slice(chunk.indexOf('{'), chunk.indexOf('}') + 1)
    const family = /font-family:\s*'([^']+)'/.exec(chunk)?.[1]
    // Google serves a legacy .ttf block and a modern .woff2 block; keep woff2 only.
    const src = /url\((https:\/\/fonts\.gstatic\.com\/[^)]+\.woff2)\)/.exec(chunk)?.[1]
    if (!family || !src) continue
    faces.push({
      family,
      style: /font-style:\s*([a-z]+)/.exec(chunk)?.[1] ?? 'normal',
      weight: Number(/font-weight:\s*(\d+)/.exec(chunk)?.[1] ?? '400'),
      src,
      block,
    })
  }
  return faces
}

/** Maps a gstatic URL onto its copy inside the mirror. */
function mirrorPath(url: string): string {
  return join(MIRROR_ROOT, url.replace('https://fonts.gstatic.com/', 'fonts.gstatic.com/'))
}

/**
 * Every page carries its own Google Fonts payload, listing only the families
 * that page uses, so all of them have to be read to end up with the full set.
 */
const faces: Face[] = []
for (const page of PAGES) {
  const html = readFileSync(join(MIRROR_ROOT, page.dir, 'index.html'), 'utf8')
  for (const id of FONT_STYLE_IDS) {
    try {
      faces.push(...parseFaces(readStyleBlock(html, id)))
    } catch {
      // Not every page inlines every block; missing ones simply contribute nothing.
    }
  }
}

const wanted = faces.filter(
  (face) =>
    KEEP_WEIGHTS.has(face.weight) &&
    (face.style === 'normal' || face.weight === 400 || face.weight === 700),
)

// The same face turns up on many pages; keep one of each.
const kept = [...new Map(wanted.map((face) => [face.src, face])).values()]

const rules: string[] = []
let copied = 0
let missing = 0

for (const face of kept) {
  const source = mirrorPath(face.src)
  const slug = face.family.toLowerCase().replace(/\s+/g, '-')
  const file = basename(source)
  const target = join(FONT_DIR, slug, file)
  try {
    mkdirSync(dirname(target), { recursive: true })
    copyFileSync(source, target)
    copied += 1
  } catch {
    missing += 1
    continue
  }
  rules.push(
    '@font-face ' +
      face.block
      .replace(/\{\s*/, '{\n  ')
      .replace(/;\s*/g, ';\n  ')
      .replace(/\s*\}$/, '\n}')
      .replace(/url\([^)]+\)/, `url('/fonts/${slug}/${file}')`),
  )
}

const out = resolve(PROJECT_ROOT, 'src/styles/fonts.css')
mkdirSync(dirname(out), { recursive: true })
writeFileSync(
  out,
  [
    '/* Generated by scripts/fonts.ts — do not edit by hand.',
    ' * Google Fonts faces used by the original Divi theme, trimmed to the',
    ' * served from public/fonts.',
    ' */',
    '',
    ...rules,
    '',
  ].join('\n'),
  'utf8',
)

const families = [...new Set(kept.map((f) => f.family))]
console.log(`fonts: ${copied} files copied, ${missing} missing`)
console.log(`families: ${families.join(', ')}`)
console.log(`wrote ${out}`)
