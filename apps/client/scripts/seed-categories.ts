/**
 * Writes shared/pnw/seed-categories.ts: the mirror's WordPress categories, as
 * the Hírkezelő seeds them into an empty database (seed-terms.ts).
 *
 *   node --experimental-strip-types scripts/seed-categories.ts
 *
 * Derived from src/data/archives.ts, which has every category archive's route
 * and label. It used to be derived at runtime, but that made the server
 * import the client's data files; since the client/server split
 * (apps/client, apps/server) the server image contains no client code, so
 * the list is written out here instead. Run it after scripts/archives.ts.
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { archives } from '../src/data/archives.ts'
import { PROJECT_ROOT } from './mirror.ts'

const seen = new Map<string, string>()
for (const archive of Object.values(archives)) {
  if (archive.kind !== 'category') continue
  // Paged category archives ("/kategoria/hirek/page/2/") are the same
  // category as the unpaged one - collapse them to one entry.
  const route = archive.route.replace(/page\/\d+\/$/, '')
  if (!seen.has(route)) seen.set(route, archive.label)
}

const lines = [...seen].map(([route, name]) => `  { route: ${JSON.stringify(route)}, name: ${JSON.stringify(name)} },`)
const out = resolve(PROJECT_ROOT, '../../shared/pnw/seed-categories.ts')
writeFileSync(
  out,
  [
    '/**',
    ' * GENERATED by apps/client/scripts/seed-categories.ts from',
    ' * apps/client/src/data/archives.ts - do not edit by hand.',
    ' *',
    " * The mirror's WordPress categories: each category archive's route and label.",
    ' */',
    'export const MIRROR_CATEGORIES: { route: string; name: string }[] = [',
    ...lines,
    ']',
    '',
  ].join('\n'),
  'utf8',
)
console.log(`seed-categories: ${seen.size} categories -> shared/pnw/seed-categories.ts`)
