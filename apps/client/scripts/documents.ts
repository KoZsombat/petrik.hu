/**
 * Writes the default documents (AGENT.md 6.20): one JSON file per page under
 * src/data/pages/, the page's design stylesheet beside it, and the registry
 * (src/data/pages/index.ts) that maps every route to its default.
 *
 * Shared by scripts/generate.ts, which converts walk.ts's output as it
 * regenerates the site, and scripts/convert-pages.ts.
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { PROJECT_ROOT } from './mirror.ts'
import { PAGES } from './pages.ts'
import { readFileSync } from 'node:fs'
import type { PageDocument } from '../../../shared/pnw/page-types.ts'
import { tsxToDocument } from './tsx-to-document.ts'

export const DATA_PAGES = resolve(PROJECT_ROOT, 'src/data/pages')

/**
 * JSON that stays readable in a diff without being huge: a value that fits on
 * one short line is printed on one line, anything bigger is broken up with a
 * single space of indent.
 */
export function compactJson(value: unknown, depth = 0): string {
  const flat = JSON.stringify(value)
  if (flat === undefined) return 'null'
  if (flat.length <= 110 || typeof value !== 'object' || value === null) return flat
  const pad = ' '.repeat(depth + 1)
  if (Array.isArray(value)) {
    return `[\n${value.map((item) => pad + compactJson(item, depth + 1)).join(',\n')}\n${' '.repeat(depth)}]`
  }
  const entries = Object.entries(value as Record<string, unknown>).filter(([, item]) => item !== undefined)
  return `{\n${entries.map(([key, item]) => `${pad}${JSON.stringify(key)}: ${compactJson(item, depth + 1)}`).join(',\n')}\n${' '.repeat(depth)}}`
}

/** Converts one generated component's source and writes its document. */
export function writeDocument(component: string, tsx: string): void {
  const document = tsxToDocument(tsx)
  mkdirSync(DATA_PAGES, { recursive: true })
  writeFileSync(resolve(DATA_PAGES, `${component}.json`), compactJson(document) + '\n', 'utf8')
}

/** src/data/pages/index.ts: every default document, with its stylesheet. */
export function writeRegistry(): void {
  const imports: string[] = []
  const entries: string[] = []
  PAGES.forEach((page, at) => {
    imports.push(`import d${at} from './${page.component}.json'`)
    if (page.kind !== 'classic') imports.push(`import './${page.component}.css'`)
    entries.push(`  ${JSON.stringify(page.route)}: { route: ${JSON.stringify(page.route)}, component: ${JSON.stringify(page.component)}, document: d${at} as unknown as PageDocument },`)
  })
  const source = `/**
 * GENERATED by scripts/documents.ts - do not edit by hand (AGENT.md 6.20).
 *
 * The default document of every mirrored page, keyed by route. A page nobody
 * edited renders from here; an edited one is a full document in the database
 * that replaces it (src/pages/DocumentPage.tsx). The page stylesheets are
 * imported here because a document cannot import CSS itself - each is scoped
 * under the page's own class, so loading all of them is harmless.
 */
import type { PageDocument } from '../../../../../shared/pnw/page-types.ts'
${imports.join('\n')}

export type PageDefault = { route: string; component: string; document: PageDocument }

export const pageDefaults: Record<string, PageDefault> = {
${entries.join('\n')}
}
`
  writeFileSync(resolve(DATA_PAGES, 'index.ts'), source, 'utf8')
}

/**
 * shared/pnw/mirror-routes.ts: which routes are mirrored pages, and what each
 * one's frame is. The server cannot import the client's bundle, but it must
 * know - an edit of a mirrored route may only be saved with that route's own
 * template and document identity (a docs page with an invented slug would
 * crash the BetterDocs frame).
 */
export function writeMirrorRoutes(): void {
  const rows = PAGES.map((page) => {
    const document = JSON.parse(readFileSync(resolve(DATA_PAGES, `${page.component}.json`), 'utf8')) as PageDocument
    const fields = [`template: ${JSON.stringify(document.template)}`]
    if (document.docsSlug) fields.push(`docsSlug: ${JSON.stringify(document.docsSlug)}`)
    if (document.post) fields.push(`postSlug: ${JSON.stringify(document.post.slug)}`)
    return `  ${JSON.stringify(page.route)}: { ${fields.join(', ')} },`
  })
  const source = `/**
 * GENERATED by scripts/documents.ts - do not edit by hand (AGENT.md 6.20).
 *
 * The routes whose page is a bundled default document, and what frames each.
 * The server (server/routes/pages.ts) accepts an edit of a mirrored route only
 * against this list.
 */
import type { PageTemplate } from './page-types.ts'

export type MirrorRoute = { template: PageTemplate; docsSlug?: string; postSlug?: string }

export const MIRROR_ROUTES: Record<string, MirrorRoute> = {
${rows.join('\n')}
}
`
  writeFileSync(resolve(PROJECT_ROOT, '../../shared/pnw/mirror-routes.ts'), source, 'utf8')
}
